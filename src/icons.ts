export type SymbolName = keyof typeof SYMBOLE;

/** Symbol als <span> mit SVG. `gefuellt`: ausgefüllte Form (für aktive Zustände). */
export function symbol(name: SymbolName, gefuellt = false): HTMLSpanElement {
  const s = document.createElement("span");
  s.className = "sym";
  s.setAttribute("aria-hidden", "true");
  s.innerHTML = SYMBOLE[name][gefuellt ? 1 : 0].replace(/ width="48" height="48"/, "");
  return s;
}
